import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { sha256Hex } from '@/lib/fingerprint/sha256';
import { buildExifJpeg, buildPlainJpeg } from './helpers/exif-jpeg';

/**
 * The manifest is repository-owned data, not hostile input. The cast is kept
 * local to this test; production code validates every external value.
 */
type FixtureRecord = Readonly<{
  id: string;
  file?: string;
  generation?: string;
  source: string;
  license: string;
  byteLength: number;
  sha256: string;
  expected: Readonly<Record<string, unknown>>;
  expectationEstablishedBy: string;
}>;

type ReferenceOutput = Readonly<{
  id: string;
  file: string;
  sourceFixture: string;
  producedBy: string;
  byteLength: number;
  sha256: string;
  notes: string;
}>;

type FixtureManifest = Readonly<{
  schemaVersion: string;
  updatedAtUtc: string;
  verificationEnvironment: string;
  notes: readonly string[];
  fixtures: readonly FixtureRecord[];
  referenceOutputs: readonly ReferenceOutput[];
  pendingCategories: readonly string[];
}>;

const manifestPath = fileURLToPath(new URL('../fixtures/manifest.json', import.meta.url));
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as FixtureManifest;

function repositoryFile(relativePath: string): Uint8Array<ArrayBuffer> {
  // Copy into a fresh ArrayBuffer view so the Node Buffer's `ArrayBufferLike`
  // backing store matches the Web Crypto input type used by `sha256Hex`.
  return new Uint8Array(
    readFileSync(fileURLToPath(new URL(`../../${relativePath}`, import.meta.url))),
  );
}

function fixture(id: string): FixtureRecord {
  const found = manifest.fixtures.find((entry) => entry.id === id);

  if (found === undefined) {
    throw new Error(`Fixture manifest is missing ${id}.`);
  }

  return found;
}

describe('fixture provenance manifest', () => {
  it('records each fixture once with a valid hash and byte length', () => {
    expect(manifest.schemaVersion).toBe('1.1');
    expect(manifest.fixtures.length).toBeGreaterThan(0);
    expect(new Set(manifest.fixtures.map((entry) => entry.id)).size).toBe(manifest.fixtures.length);
    expect(new Set(manifest.referenceOutputs.map((entry) => entry.id)).size).toBe(
      manifest.referenceOutputs.length,
    );

    for (const entry of manifest.fixtures) {
      expect(entry.sha256).toMatch(/^[a-f0-9]{64}$/);
      expect(Number.isSafeInteger(entry.byteLength)).toBe(true);
      expect(entry.byteLength).toBeGreaterThan(0);
      expect(entry.source.length).toBeGreaterThan(0);
      expect(entry.license.length).toBeGreaterThan(0);
      expect(entry.expectationEstablishedBy.length).toBeGreaterThan(0);
      expect(Object.keys(entry.expected).length).toBeGreaterThan(0);
      // A fixture is either generated by test code or stored as a committed file.
      expect(entry.file !== undefined || entry.generation !== undefined).toBe(true);
    }
  });

  it('keeps every committed fixture file identical to its recorded hash', async () => {
    const stored = manifest.fixtures.filter((entry) => entry.file !== undefined);

    expect(stored.length).toBeGreaterThan(0);

    for (const entry of stored) {
      const bytes = repositoryFile(entry.file as string);

      expect(bytes.byteLength).toBe(entry.byteLength);
      await expect(sha256Hex(bytes)).resolves.toBe(entry.sha256);
    }
  });

  it('keeps the synthetic EXIF fixture bytes identical to the recorded hash', async () => {
    const bytes = buildExifJpeg();
    const entry = fixture('synthetic-exif-jpeg');

    expect(bytes.byteLength).toBe(entry.byteLength);
    await expect(sha256Hex(bytes)).resolves.toBe(entry.sha256);
  });

  it('keeps the synthetic plain JPEG bytes identical to the recorded hash', async () => {
    const bytes = buildPlainJpeg();
    const entry = fixture('synthetic-plain-jpeg');

    expect(bytes.byteLength).toBe(entry.byteLength);
    await expect(sha256Hex(bytes)).resolves.toBe(entry.sha256);
  });

  it('keeps recorded SDK output byte-identical to the hash its expectations rest on', async () => {
    const recorded = manifest.referenceOutputs.find(
      (entry) => entry.id === 'c2pa-sdk-recorded-output',
    );

    expect(recorded).toBeDefined();

    const bytes = repositoryFile((recorded as ReferenceOutput).file);

    expect(bytes.byteLength).toBe((recorded as ReferenceOutput).byteLength);
    await expect(sha256Hex(bytes)).resolves.toBe((recorded as ReferenceOutput).sha256);
    expect((recorded as ReferenceOutput).producedBy).toContain('c2pa-web 0.15.4');
  });

  it('keeps every reference output stored, hashed, and attributed', async () => {
    expect(manifest.referenceOutputs.length).toBeGreaterThan(0);

    for (const output of manifest.referenceOutputs) {
      expect(output.sha256).toMatch(/^[a-f0-9]{64}$/);
      expect(output.producedBy.length).toBeGreaterThan(0);
      expect(output.notes.length).toBeGreaterThan(0);
      expect(manifest.fixtures.some((entry) => entry.id === output.sourceFixture)).toBe(true);

      const bytes = repositoryFile(output.file);

      expect(bytes.byteLength).toBe(output.byteLength);
      await expect(sha256Hex(bytes)).resolves.toBe(output.sha256);
    }
  });

  it('does not record signer trust as trusted without a configured trust policy result', () => {
    const presenceFixtures = manifest.fixtures.filter(
      (entry) => entry.expected['manifestPresence'] === 'present',
    );

    expect(presenceFixtures.length).toBeGreaterThan(0);

    // The no-anchor policy is what this build actually applies: no fixture may
    // claim a trusted signer, and every one must name the policy it was judged by.
    for (const entry of presenceFixtures) {
      expect(entry.expected['signerTrust']).not.toBe('trusted');
      expect(entry.expected['trustPolicyId']).toBe(
        'originlens-embedded-only-no-trust-anchors-v1',
      );
    }
  });

  it('still lists the credential fixtures that remain unverified', () => {
    expect(manifest.pendingCategories.length).toBeGreaterThan(0);
    expect(manifest.pendingCategories.join(' ')).toMatch(/credential/i);
    expect(manifest.notes.join(' ')).toMatch(/recorded output of the pinned SDK/);
    expect(manifest.notes.join(' ')).toMatch(/reference manifest store/i);
  });
});
